// Q-05: dump the real metric names, label sets, datasource UIDs and histogram `le` values to stdout as markdown.
// Usage: node tools/metric-names.mjs > docs/METRIC_NAMES.lock.md   (make metric-names)
// Env: PROM_URL (default http://localhost:9090), GRAFANA_URL (default http://localhost:3000), GRAFANA_AUTH (default admin:admin)
const PROM = process.env.PROM_URL || 'http://localhost:9090';
const GRAFANA = process.env.GRAFANA_URL || 'http://localhost:3000';
const AUTH = Buffer.from(process.env.GRAFANA_AUTH || 'admin:admin').toString('base64');
const PREFIX = /^(nocook_|oms_|k6_|http_server_requests|jvm_|hikaricp_|process_|system_)/;

const prom = async (path) => {
  const r = await fetch(`${PROM}/api/v1/${path}`);
  if (!r.ok) throw new Error(`prometheus ${path}: ${r.status}`);
  return (await r.json()).data;
};

const names = (await prom('label/__name__/values')).filter((n) => PREFIX.test(n)).sort();
const histograms = names.filter((n) => n.endsWith('_bucket'));

const labelsOf = async (name) => {
  const series = await prom(`series?match[]=${encodeURIComponent(name)}`);
  const m = new Map();
  for (const s of series) {
    for (const [k, v] of Object.entries(s)) {
      if (k === '__name__') continue;
      if (!m.has(k)) m.set(k, new Set());
      m.get(k).add(v);
    }
  }
  return m;
};

const num = (a, b) => parseFloat(a) - parseFloat(b);
const out = [];
out.push('# METRIC_NAMES.lock.md');
out.push('');
out.push('Generated by `make metric-names` (`node tools/metric-names.mjs`) from the live stack. Dashboards are written against this file, not against OBSERVABILITY.md §2.');
out.push(`Generated: ${new Date().toISOString()}`);
out.push('');

out.push('## Datasources (GET :3000/api/datasources)');
out.push('');
out.push('| name | uid | type |');
out.push('|---|---|---|');
try {
  const r = await fetch(`${GRAFANA}/api/datasources`, { headers: { Authorization: `Basic ${AUTH}` } });
  if (!r.ok) throw new Error(String(r.status));
  for (const d of await r.json()) out.push(`| ${d.name} | \`${d.uid}\` | ${d.type} |`);
} catch (e) {
  out.push(`| (grafana unreachable: ${e.message}) | | |`);
}
out.push('');

out.push('## Metric names');
out.push('');
out.push('Series names as stored in Prometheus (`_bucket/_count/_sum` of one histogram are collapsed to the base). Labels exclude `job`, `service_name`, `le`; every nocook series also has `replica`.');
out.push('');
const bases = new Set();
const single = [];
for (const n of names) {
  const hist = n.replace(/_(bucket|count|sum)$/, '');
  if (/_(bucket|count|sum)$/.test(n) && names.includes(`${hist}_bucket`)) bases.add(hist);
  else single.push(n);
}
const rows = [...[...bases].map((b) => ({ n: `${b}_{bucket,count,sum}`, key: b, kind: 'histogram' })), ...single.map((n) => ({ n, key: n, kind: n.endsWith('_total') ? 'counter' : 'gauge' }))].sort((a, b) => a.n.localeCompare(b.n));
out.push('| name | kind | labels (distinct values, max 8 shown) |');
out.push('|---|---|---|');
const leByHist = new Map();
for (const r of rows) {
  const series = r.kind === 'histogram' ? `${r.key}_bucket` : r.key;
  const lm = await labelsOf(series);
  if (r.kind === 'histogram') leByHist.set(r.key, [...(lm.get('le') || [])].sort(num));
  const parts = [];
  for (const [k, vs] of [...lm.entries()].sort()) {
    if (['job', 'service_name', 'le'].includes(k)) continue;
    const arr = [...vs].sort();
    parts.push(`${k}=${arr.length > 8 ? `${arr.slice(0, 8).join('|')}|… (${arr.length})` : arr.join('|')}`);
  }
  const jobs = [...(lm.get('job') || [])].sort().join(',');
  out.push(`| \`${r.n}\` | ${r.kind} | ${parts.join('; ') || '-'}${jobs ? ` · job=${jobs}` : ''} |`);
}
out.push('');

out.push('## Histogram `le` values (distinct)');
out.push('');
for (const [h, les] of [...leByHist.entries()].sort()) {
  if (!/^(nocook_|oms_|http_server_requests_seconds|k6_http_req_duration|k6_iteration_duration)/.test(h)) continue;
  out.push(`### ${h}`);
  out.push('');
  out.push(`${les.length} buckets: ${les.map((l) => `\`${l}\``).join(' ')}`);
  out.push('');
}

out.push('## Notes for dashboard authors');
out.push('');
out.push('- Latency histograms are in **seconds** (`nocook_*_seconds`, `http_server_requests_seconds`); k6 trends are in **milliseconds** (`k6_http_req_duration_milliseconds`).');
out.push('- SLO bucket boundaries are exact strings: 0.3 / 2 / 3 (see `le` lists above). Use `le="2"`, `le="0.3"`, `le="3"`.');
out.push('- ACK API uri label value is the route template `/api/cases/{caseId}/ack` (job=nocook).');
out.push('- Zero-valued counters may be absent until first increment (e.g. `k6_dropped_iterations_total`): wrap with `or vector(0)`.');
out.push('- Per-replica label is `replica`; service label is `service_name` (also `job`).');
out.push('');
console.log(out.join('\n'));
